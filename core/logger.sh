#!/bin/bash

# =========================================================
# CORES
# =========================================================

VERDE="\033[1;32m"
AMARELO="\033[1;33m"
VERMELHO="\033[1;31m"
AZUL="\033[1;34m"
CYAN="\033[1;36m"
BRANCO="\033[1;37m"
RESET="\033[0m"

# =========================================================
# LINHA
# =========================================================

linha() {

    echo -e "${AZUL}============================================================${RESET}"
}

# =========================================================
# TÍTULO
# =========================================================

titulo() {

    linha

    echo -e "${BRANCO} $1 ${RESET}"

    linha

    echo
}

# =========================================================
# MENU
# =========================================================

menu() {

    echo -e "${CYAN}$1${RESET}"
}

# =========================================================
# STATUS OK
# =========================================================

status_ok() {

    printf "%-65s ${VERDE}[ OK ]${RESET}\n" "$1"
}

# =========================================================
# STATUS AVISO
# =========================================================

status_warn() {

    printf "%-65s ${AMARELO}[ ! ]${RESET}\n" "$1"
}

# =========================================================
# STATUS ERRO
# =========================================================

status_erro() {

    printf "%-65s ${VERMELHO}[ ERRO ]${RESET}\n" "$1"
}

# =========================================================
# PAUSA
# =========================================================

pausa() {

    echo

    read -p "Pressione ENTER para continuar..." < /dev/tty
}

# =========================================================
# SPINNER
# =========================================================

spinner() {

    PID=$1

    while ps -p $PID >/dev/null 2>&1
    do

        for i in '/' '-' '\\' '|'
        do

            printf "\r${CYAN}[%c] Processando...${RESET}" "$i"

            sleep 0.1
        done
    done

    printf "\r                                        \r"
}

# =========================================================
# PROGRESSO
# =========================================================

progresso() {

    TAMANHO=$1

    printf "${CYAN}["

    for ((i=0; i<$TAMANHO; i++))
    do

        printf "#"

        sleep 0.02
    done

    printf "]${RESET}\n"
}